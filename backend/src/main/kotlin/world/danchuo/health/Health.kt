 * складывает её в вечернем окне дня и через шов `checklist` ставит производный пункт
 * «дневник перед сном» (§5.6). Внимание на асимметрию дат: у сна день = день ПРОБУЖДЕНИЯ
 * (сессия в 01:00 уходит в наступивший день), у дневника — день, чей ВЕЧЕР идёт (запись
 * в 01:00 закрывает уходящий). Оба правила верные, но противоположные.
 *
