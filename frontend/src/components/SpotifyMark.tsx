/**
 * Знак Spotify (PRD §5.5, DESIGN §7.5). Отдельный компонент, а не глиф в [Icon]: набор
 * волны 01 — одноцветные line-символы на `currentColor`, а этот знак двуцветный по своей
 * природе — диск и вырезанные в нём три дуги.
 *
 * Цвета берутся из окружения, потому что правило бренда зависит от подложки: зелёный диск
 * разрешён **только на чёрном или белом**, на любом другом фоне полагается монохром. Диск
 * красится `currentColor` (то есть цветом строки, в которой знак стоит), дуги — токеном
 * `--spotify-mark-hole`, который волна ставит в цвет своей подложки. Так один компонент
 * даёт и зелёный знак на чёрной плашке PRIME, и чёрный на белом облаке Obscura.
 *
 * По умолчанию знак НЕ виден (`.spotify-mark { display: none }` в common.css): волна 01 его
 * не заводила, и появление знака сдвинуло бы её эталоны. Волна включает его у себя в скине.
 */
export function SpotifyMark({ size = 18 }: { size?: number }) {
  return (
    <svg
      className="spotify-mark"
      width={size}
      height={size}
      /* ⚠️ viewBox с полем, а не `0 0 24 24`: диск знака описан как `r=12` из центра `12,12`,
         то есть КАСАЕТСЯ всех четырёх границ кадра. Крайние пиксели тангенса при
         растеризации срезались — на 18px это читалось «кружок чуть обрезан» (замечание
         владельца, обе тёмные волны). Полшага поля со всех сторон возвращают окружности
         целый край; координаты дуг не трогаются. */
      viewBox="-0.6 -0.6 25.2 25.2"
      role="img"
      aria-label="Spotify"
      style={{ flexShrink: 0 }}
    >
      <circle cx="12" cy="12" r="12" fill="currentColor" />
      {/* Три дуги — ЗАЛИВКОЙ по настоящей геометрии знака, а не обводкой по прикидке.
          Обводка круглым торцом рисует дугу постоянной толщины, а у знака дуги к концам
          сходят на нет; на 16 пикселях эта разница читалась «мыльным» краем (замечание
          владельца по волне 02). Заливка — та же форма, что в векторе Spotify, поэтому
          знак остаётся чётким на любом кегле. */}
      <g fill="var(--spotify-mark-hole, #121212)">
        <path d="M17.521 17.34c-.24.359-.66.48-1.021.24-2.82-1.74-6.36-2.101-10.561-1.141-.418.122-.779-.179-.899-.539-.12-.421.18-.78.54-.9 4.56-1.021 8.52-.6 11.64 1.32.42.18.479.659.301 1.02" />
        <path d="M18.961 14.04c-.301.42-.841.6-1.262.3-3.239-1.98-8.159-2.58-11.939-1.38-.479.12-1.02-.12-1.14-.6-.12-.48.12-1.021.6-1.141C9.6 9.9 15 10.561 18.72 12.84c.361.181.54.78.241 1.2" />
        <path d="M19.081 10.68C15.24 8.4 8.82 8.16 5.16 9.301c-.6.179-1.2-.181-1.38-.721-.18-.601.18-1.2.72-1.381 4.26-1.26 11.28-1.02 15.721 1.621.539.3.719 1.02.419 1.56-.299.421-1.02.599-1.559.3" />
      </g>
    </svg>
  );
}
