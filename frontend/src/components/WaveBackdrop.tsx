"use client";

import { useEffect, useMemo, useRef } from "react";
import type { DaySummary } from "@/lib/api/types";
import { buildRibbon } from "@/lib/waveRibbon";

/**
 * Фоновый слой волны (DESIGN §10.2) — **общий шов, а не часть волны 03**.
 *
 * До сих пор фон волны был чистым CSS: волна 02 рисует небо и облака псевдоэлементами,
 * и этого хватало, потому что фон ничего не знал о данных. Волне 03 «PRIME» фоном служит
 * сама лента прожитых дней, а она приезжает из API и меняется вместе с окном календаря —
 * такое из CSS не достать. Поэтому слой живёт компонентом.
 *
 * Чтобы это не сломало правило «новая волна = запись в БД, без правок кода» (§10.1), шов
 * сделан **волна-агностичным**: разметка есть всегда, `common.css` держит её выключенной
 * (`display: none`), а волна включает и оформляет её у себя в скине. Волне, которой фон не
 * нужен, он не стоит ничего — ни узла в раскладке, ни кадра на отрисовке.
 *
 * Заполнение экрана — императивное, не через состояние: лента дублируется до тех пор, пока
 * не перестанет помещаться, а это измерение, и на каждый его шаг рендерить React-дерево
 * незачем. React владеет самим узлом, содержимым узла владеет этот эффект.
 */

/**
 * Потолок удвоений: страховка от бесконечного цикла, если измерение вдруг соврёт. Двадцать
 * шагов — это лента, повторённая миллион раз; ни один экран столько не просит, поэтому
 * дойти до потолка можно только на вранье измерения.
 */
const MAX_DOUBLINGS = 20;

/**
 * Потолок длины текста — вторая страховка, уже от вранья ДРУГОГО рода: `scrollHeight`,
 * который не растёт вместе с содержимым (обрезка строк у будущей волны), удвоения не
 * останавливает вовсе. 300 000 символов с запасом закрывают 8K-стену и стоят полмегабайта.
 */
const MAX_CHARS = 300_000;

/** Тот же разделитель, что внутри ленты, — стык дублей не должен быть заметен. */
const DOT = " · ";

export function WaveBackdrop({
  summaries,
  today,
  wave,
}: {
  summaries: DaySummary[];
  /** Опора «сегодня» (MSK): дни после неё на холст не едут — они ещё не прожиты. */
  today: string;
  wave: string | null;
}) {
  const ref = useRef<HTMLParagraphElement>(null);
  const ribbon = useMemo(() => buildRibbon(summaries, today), [summaries, today]);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;

    // Слой пережил размонтирование только в одном месте — в отложенной пересборке по
    // шрифтам; флаг гасит её, чтобы она не писала в оторванный от документа узел.
    let alive = true;

    const fill = () => {
      if (!alive) return;
      // Волна фон не включала — не тратим ни измерения, ни узлов текста.
      if (!ribbon || getComputedStyle(el).display === "none") {
        el.textContent = "";
        return;
      }
      el.textContent = ribbon;
      // Нулевая высота — верстки ещё нет (SSR-гидрация, скрытый таб, jsdom): одного
      // прохода достаточно, дублировать вслепую нечего.
      if (el.clientHeight === 0) return;
      let text = ribbon;
      // Текст УДВАИВАЕТСЯ, а не растёт на один дубль за проход. Стена бывает во много раз
      // выше ленты: браузерный зум наружу растягивает вьюпорт (на 25% площадь больше в
      // шестнадцать раз), а на телефоне слой равен всей странице, а не экрану. Линейный шаг
      // упирался в свой потолок раньше, чем закрывал стену, и низ холста оставался пустым
      // (замер на 5000×2800: сорок дублей не дотянули до края). Удвоение доходит до любой
      // высоты за десяток шагов и промахивается не больше чем вдвое — лишний хвост всё равно
      // срезан `overflow: hidden`.
      for (
        let i = 0;
        i < MAX_DOUBLINGS && text.length < MAX_CHARS && el.scrollHeight <= el.clientHeight;
        i++
      ) {
        text += DOT + text;
        el.textContent = text;
      }
    };

    fill();

    // Пересборка по готовности шрифтов: лента набрана моноширинным, а до его загрузки
    // строки меряются подменным набором — заполнение, честное на старте, после подмены
    // не достаёт до края. Наблюдатель размеров этот случай не ловит: коробка слоя не
    // меняется, меняются метрики текста внутри.
    document.fonts?.ready.then(fill).catch(() => {});

    // Наблюдаем за самим слоем, а не за окном: он растянут на всю страницу, поэтому ловит
    // одним источником и ресайз, и зум, и смену ориентации, и подросшую от новых данных
    // страницу. Дубли меняют scrollHeight, но не border-box, так что наблюдатель себя не
    // будит. `undefined` — jsdom-тесты без ResizeObserver: там хватает первого прохода.
    let frame = 0;
    const observer =
      typeof ResizeObserver === "undefined"
        ? null
        : new ResizeObserver(() => {
            cancelAnimationFrame(frame);
            frame = requestAnimationFrame(fill);
          });
    observer?.observe(el);
    return () => {
      alive = false;
      cancelAnimationFrame(frame);
      observer?.disconnect();
    };
    // `wave` в зависимостях: своп волны меняет `display` слоя, и ленту надо пересобрать
    // под новую высоту (или стереть, если новая волна фон не рисует).
  }, [ribbon, wave]);

  return (
    <div className="wave-backdrop" aria-hidden="true">
      <p className="wave-backdrop-ribbon" ref={ref} />
    </div>
  );
}
