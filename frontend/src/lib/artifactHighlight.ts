import type { ArtifactBoxView } from "./api/types";

/**
 * Насколько рамка подсветки шире самой находки — доля её собственного размера, добавляемая
 * с каждой стороны (PRD §5.12, DESIGN §7.5).
 *
 * Точная рамка по краю предмета читается как обводка, а задача другая — **показать, куда
 * смотреть** (требование владельца — «область рядом», а не контур). Плюс это страховка:
 * у модели рамка бывает чуть смещена, и запас прячет мелкий промах.
 *
 * ⚠️ Не путать с `artifactBox.ts` — там геометрия предметов в бегущей строке, другая задача.
 */
export const HIGHLIGHT_PAD = 0.15;

/** Рамка в долях кадра, готовая к отрисовке: начало + размеры. */
export interface HighlightRect {
  x0: number;
  y0: number;
  width: number;
  height: number;
}

/**
 * Расширить рамку на [pad] её ширины/высоты в каждую сторону, не вылезая за кадр.
 *
 * Расширяем **при отрисовке, а не в данных**: в БД лежит то, что действительно ответила
 * модель, поэтому запас можно переназначить, ничего не перепрогоняя. Клампинг по краям
 * обязателен — у предмета возле границы кадра рамка иначе ушла бы в минус.
 */
export function padHighlight(box: ArtifactBoxView, pad: number = HIGHLIGHT_PAD): HighlightRect {
  const dx = (box.x1 - box.x0) * pad;
  const dy = (box.y1 - box.y0) * pad;
  const x0 = Math.max(0, box.x0 - dx);
  const y0 = Math.max(0, box.y0 - dy);
  const x1 = Math.min(1, box.x1 + dx);
  const y1 = Math.min(1, box.y1 + dy);
  // Округляем: сырая арифметика долей даёт в CSS значения вроде `2.500000000000001%`.
  // Тысячных долей процента с запасом хватает на любой размер кадра.
  const round = (v: number) => Math.round(v * 1e5) / 1e5;
  return { x0: round(x0), y0: round(y0), width: round(x1 - x0), height: round(y1 - y0) };
}
