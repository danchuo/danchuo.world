/**
 * Запасная обложка: какую из фирменных плашек Spotify показать вместо картинки (DESIGN §7.1).
 *
 * Обложка приезжает с CDN Spotify, и он иногда её не отдаёт (а у части треков её нет вовсе).
 * Пустой серый квадрат на этом месте читается поломкой вёрстки, поэтому вместо него рисуется
 * знак сервиса на цветном поле.
 *
 * Плашек пять, и это число не выбрано, а посчитано: столько существует сочетаний знака и фона,
 * законных по гайдлайну Spotify (зелёный логотип — только на чёрном или белом; там, где зелёный
 * нельзя, знак идёт чёрным или белым). Композиция у всех одна — знак по центру: кадрировать,
 * растягивать и разворачивать знак гайдлайн запрещает, так что варьируется ровно то, что
 * варьировать разрешено.
 */

/** Сколько плашек в наборе. Цвета — в `common.css`, по `[data-plate]`. */
export const COVER_PLATES = 5;

/**
 * Номер плашки для трека: **детерминированно** по ключу (ссылка на трек, а без неё — название).
 *
 * Детерминированность здесь не гигиена, а требование: случайный выбор менял бы плашку на
 * каждой перерисовке, и список недавних мигал бы цветами сам по себе, без единого нового
 * данного. Один трек — всегда одна плашка, в том числе после F5.
 *
 * Хэш — FNV-1a: ссылки Spotify отличаются только хвостом идентификатора, и наивная сумма кодов
 * складывала бы весь список в один-два цвета. FNV перемешивает младшие биты умножением, поэтому
 * соседние ключи расходятся.
 */
export function coverPlate(seed: string | null): number {
  if (!seed) return 0;
  let h = 0x811c9dc5;
  for (let i = 0; i < seed.length; i += 1) {
    h ^= seed.charCodeAt(i);
    // Умножение на простое 16777619 в 32-битной арифметике; `Math.imul` — чтобы не терять
    // старшие биты на переполнении double.
    h = Math.imul(h, 0x01000193);
  }
  return Math.abs(h) % COVER_PLATES;
}
