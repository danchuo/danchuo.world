/**
 * Номер дня жизни владельца борда: дата → «какой это по счёту день с рождения».
 * Подсказка на дате плитки «Сегодня» (DESIGN §4): сама дата остаётся датой, а её
 * место в жизни всплывает только при наведении.
 *
 * Арифметика — над ISO-строками в UTC-полночь, как во всём каноне дат (см. [./date]):
 * так високосные годы и переходы на летнее время не сдвигают счёт на день.
 */

/** Первый день жизни — день рождения, он же день №1 (не нулевой). */
export const BIRTH_DATE = "2002-06-06";

/**
 * Номер дня жизни для даты (`YYYY-MM-DD`), день рождения = 1.
 * До рождения — `null`: у такого дня номера нет, и подписывать его нечем.
 */
export function lifeDayNumber(iso: string): number | null {
  const ms = Date.parse(`${iso}T00:00:00Z`) - Date.parse(`${BIRTH_DATE}T00:00:00Z`);
  const days = Math.round(ms / 86_400_000);
  return days < 0 ? null : days + 1;
}

/**
 * Подпись дня жизни по-русски: «8833-й день жизни». Наращение всегда «-й» —
 * у порядковых мужского рода в именительном падеже (второй, восьмой, сороковой)
 * после цифр пишется одна последняя буква, то есть «8-й», а не «8-ой».
 */
export function lifeDayLabel(iso: string): string | null {
  const n = lifeDayNumber(iso);
  return n == null ? null : `${n}-й день жизни`;
}
