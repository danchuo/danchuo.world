import type { PodcastEpisodeView } from "./api/types";

/**
 * Формулы карточки прослушанного подкаста (PRD §5.6) — то, что нужно знать до отрисовки:
 * какой заход показать у остановки и что написать про минуты.
 */

/**
 * Карточка для остановки с номером [occurrence] (1-based). Карточки раздаются по порядку, и их
 * может быть МЕНЬШЕ, чем закрытых остановок: отметки считаются по сумме минут за сутки, а
 * карточки — по заходам. Марафон в один присест закрывает обе остановки и приносит одну
 * карточку — вторая остаётся без ховера, и это норма, а не потеря данных: заход-то был один.
 */
export function episodeForStop(
  episodes: PodcastEpisodeView[] | undefined,
  occurrence: number,
): PodcastEpisodeView | null {
  return episodes?.[occurrence - 1] ?? null;
}

/**
 * Подпись к куску — та же роль, что у «прочитано» на карточке книги, и набирается она теми же
 * классами: вопрос у книги и у выпуска один, и набор у него обязан быть один.
 */
export const LISTENED_CAPTION = "прослушано";

/**
 * Единица минут в подписях карточки — одна на все три из них, чтобы «мин» не разъехалась по
 * файлу. Отдельного элемента в разметке у неё НЕТ: строка куска красится целиком, вместе с
 * единицей (решение владельца), и делить её не на что.
 */
export const MINUTES_UNIT = "мин";

/**
 * Сколько слушали за заход: «50 мин».
 *
 * Стоит НАД пройденным куском и тише него — отвечает «сколько всего», чтобы не вычитать одно
 * из другого в уме. У книги такой строки нет и не нужно: проценты там и есть весь ответ.
 *
 * **Часов начала на карточке нет** (решение владельца): «во сколько я включил» — не тот вопрос,
 * который она задаёт. Момент захода бэкенд наружу и не отдаёт, хотя хранит: по нему заходы
 * упорядочены и склеены.
 */
export function listenedLabel(episode: PodcastEpisodeView): string {
  return `${episode.listenedMinutes} ${MINUTES_UNIT}`;
}

/**
 * Пройденный кусок выпуска: «45 → 95 мин». Тот же ответ и та же стрелка, что у процентов
 * книги (`35% → 42%`) — вопрос-то один и тот же, разнятся только единицы.
 *
 * `null` — обеих границ нет (заход записан до того, как мы стали смотреть окно) либо они
 * совпали: «45 → 45» не кусок, а точка, и говорить ею нечего.
 */
export function stretchLabel(episode: PodcastEpisodeView): string | null {
  const from = episode.startMinute;
  const to = episode.endMinute;
  if (typeof from !== "number" || typeof to !== "number") return null;
  if (to <= from) return null;
  return `${from} → ${to} ${MINUTES_UNIT}`;
}

/**
 * «47 из 48 мин», а без длительности — просто «47 мин».
 *
 * Прослушанное зажимается длительностью. Переслушанный кусок честно копится в минутах (слушал —
 * значит слушал), но «49 из 48» на карточке читалось бы как сбой счётчика, а не как повтор.
 */
export function minutesLabel(minutes: number, durationMinutes: number | null | undefined): string {
  if (typeof durationMinutes !== "number") return `${minutes} ${MINUTES_UNIT}`;
  return `${Math.min(minutes, durationMinutes)} из ${durationMinutes} ${MINUTES_UNIT}`;
}
