/**
 * Ветки дерева для списка проектов — редакция «консоль» (DESIGN §7.8).
 *
 * `tree` метит последний элемент уровня углом, остальные — тройником. Считаем по ВСЕМУ
 * списку, а не по видимому окну: при прокрутке настоящий последний уезжает под срез, и
 * видимые строки честно остаются тройниками — именно это и значит «дерево продолжается за
 * краем». Подгонять угол под нижнюю видимую строку нельзя: она не последняя, и угол соврал
 * бы, что список кончился.
 *
 * Отдаём ВИД ветки, а не глиф: рисует её CSS линиями (`.project-branch`), потому что
 * box-drawing-знаков в подмножестве моношрифта борда нет — см. docs/pitfalls.md.
 */

/** `corner` — угол, закрывающий список; `tee` — тройник, у которого ветка продолжается. */
export type BranchKind = "tee" | "corner";

/** Вид ветки для строки `index` из `total`. Чистая функция — ни DOM, ни данных проекта. */
export function treeBranch(index: number, total: number): BranchKind {
  return index === total - 1 ? "corner" : "tee";
}
